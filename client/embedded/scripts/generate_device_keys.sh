#!/usr/bin/env bash
set -euo pipefail

# Generate a fresh RSA keypair and embed into firmware + web config

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
embedded_dir="$(cd "$script_dir/.." && pwd)"
keys_dir="$embedded_dir/keys"
private_pem="$keys_dir/device_private.pem"
public_pem="$keys_dir/device_public.pem"
device_private_header="$embedded_dir/src/DevicePrivateKey.h"
web_public_ts="$embedded_dir/../web/src/config/devicePublicKey.ts"

mkdir -p "$keys_dir"
mkdir -p "$(dirname "$device_private_header")"
mkdir -p "$(dirname "$web_public_ts")"

echo "Generating device RSA keypair..."
openssl genpkey -algorithm RSA -out "$private_pem" -pkeyopt rsa_keygen_bits:2048
openssl rsa -pubout -in "$private_pem" -out "$public_pem"

# Escape newlines for C string literal
escaped_private=$(awk '{printf("%s\\n", $0)}' "$private_pem")

cat > "$device_private_header" <<EOF
/*
 * ===============================================================================
