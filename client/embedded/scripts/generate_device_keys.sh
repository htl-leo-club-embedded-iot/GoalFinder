 * distributed under the License is distributed on an "AS IS" BASIS,
 * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 * See the License for the specific language governing permissions and
 * limitations under the license.
 * - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
 * All trademarks used in this document are property of their respective owners.
 * ===============================================================================
 */


#pragma once

static const char DEVICE_PRIVATE_KEY_PEM[] = "$escaped_private";
EOF

echo "Writing web public key: $web_public_ts"
public_key_content=$(cat "$public_pem")
{
	printf '%s\n' '// Auto-generated by generate_device_keys.sh - do not edit'
	printf '%s' 'export const DEVICE_PUBLIC_KEY_PEM = '\n
	printf '%s' '\`'
	printf '%s' "$public_key_content"
	printf '%s\n' '\`;'
} > "$web_public_ts"

exit 0
